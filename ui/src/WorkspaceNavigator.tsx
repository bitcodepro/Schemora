import DependencyPaths from './DependencyPaths';
import { useEffect, useState, useMemo } from 'react';
import { request, errorMessage, sessionToken } from './api';

import { t, getLocale } from './i18n';
import { useLocale } from './i18nReact';
import { useDisplayPath, useWorkspaces } from './workspaceContext';
import type { Workspace, Catalog, Graph, Database } from './types';
type Dependencies = {
  databases: { id: string; name: string; sourcePath: string; objects: { id: string; schema: string; name: string; kind: string }[] }[];
  recipes: { id: string; name: string; status: string; dependencies: { tableId: string; columnName?: string }[] }[];
};
export default function WorkspaceNavigator({
  onObject,
  onRecipe,
}: {
  onObject: (graph: Graph, db: Database) => void;
  onRecipe: (workspace: string, recipe: string) => void;
}) {
  useLocale();
  const { workspaces, workspaceId: id, reload } = useWorkspaces();
  const displayPath = useDisplayPath();
  const [catalog, setCatalog] = useState<Catalog | null>(null),
    [dependencies, setDependencies] = useState<Dependencies | null>(null),
    [query, setQuery] = useState(''),
    [selected, setSelected] = useState(''),
    [error, setError] = useState(''),
    [busy, setBusy] = useState(false);
  const [offsets, setOffsets] = useState<Record<string, number>>({});
  const [refresh, setRefresh] = useState(0);
  const [reportSections, setReportSections] = useState({ objects: true, relations: true, evidence: true, recipes: false });
  const key = 'navigator:' + id;
  useEffect(() => {
    setCatalog(null);
    setDependencies(null);
    setSelected('');
    setOffsets({});
    if (!id) return;
    try {
      setQuery(localStorage.getItem(key) || '');
    } catch {
      setQuery('');
    }
    const c = new AbortController();
    void Promise.all([
      request<Catalog>(`/api/workspaces/${id}/catalog`, { signal: c.signal }),
      request<Dependencies>(`/api/workspaces/${id}/recipe-dependencies?includeRecipes=false`, { signal: c.signal }),
    ])
      .then(([a, b]) => {
        setCatalog(a);
        setDependencies(b);
      })
      .catch(e => {
        if (!c.signal.aborted) setError(errorMessage(e, t('Unable to load workspace navigation.')));
      });
    return () => c.abort();
  }, [id, key, refresh]);
  // The tutorial project is generated by Schemora itself, so it can be built without asking for project trust.
  // With a .NET SDK present this replaces the partial static model with an authoritative DACPAC; the workspace
  // panel picks the job up from session storage and shows its progress. Without an SDK the static model stays.
  async function startTutorialBuild(workspaceId: string) {
    try {
      const environment = await request<{ capabilities: { name: string; available: boolean }[] }>('/api/diagnostics');
      if (!environment.capabilities.some(capability => capability.name === '.NET SDK' && capability.available)) return;
      const job = await request<{ id: string }>(`/api/workspaces/${encodeURIComponent(workspaceId)}/scan`, {
        method: 'POST',
        body: JSON.stringify({ mode: 'rebuild', trustProjects: true }),
      });
      sessionStorage.setItem(`schemora.job.${workspaceId}`, job.id);
    } catch {
      /* The tutorial is usable with its static model; the workspace page still offers Rebuild. */
    }
  }
  async function demo() {
    setBusy(true);
    setError('');
    try {
      const result = await request<{ workspace: Workspace; database: Database; recipeId: string }>('/api/tutorial', { method: 'POST' });
      await startTutorialBuild(result.workspace.id);
      await reload(result.workspace.id);
    } catch (e) {
      setError(errorMessage(e, t('Unable to create tutorial.')));
    } finally {
      setBusy(false);
    }
  }
  const within = (file: string, folder: string) => {
    const a = file.replaceAll('\\', '/').toLowerCase();
    const b = folder.replaceAll('\\', '/').toLowerCase().replace(/\/$/, '');
    return a === b || a.startsWith(b + '/');
  };
  const groups = useMemo(() => {
    const values = new Map<string, NonNullable<Dependencies['databases']>>();
    for (const db of dependencies?.databases || []) {
      const source = catalog?.sources
        .filter(p => ['sqlProject', 'csharpProject'].includes(p.kind))
        .sort((a, b) => b.path.length - a.path.length)
        .find(p => db.sourcePath === p.path || within(db.sourcePath, p.path.replace(/[^\\/]+$/, '')));
      const repo = catalog?.sources.filter(p => p.kind === 'repository').find(p => within(db.sourcePath, p.path));
      const label = (repo?.path || catalog?.workspace.name || '') + ' → ' + (source?.path || db.sourcePath);
      values.set(label, [...(values.get(label) || []), db]);
    }
    return [...values];
  }, [dependencies, catalog]);
  const repositories = useMemo(
    () =>
      [...new Set(groups.map(([label]) => label.split(' → ')[0]))].map(
        repository => [repository, groups.filter(([label]) => label.split(' → ')[0] === repository)] as const,
      ),
    [groups],
  );
  return (
    <section className="settings-card product-controls" aria-label={t('Workspace navigator')}>
      <h2>{t('Workspace navigator')}</h2>
      <details open={!workspaces.length}>
        <summary>{t('Getting started')}</summary>
        <ol>
          <li>{t('Open your project or load the tutorial.')}</li>
          <li>{t('Scan the schema and review relationships.')}</li>
          <li>{t('Open a recipe, enter IDs and generate SQL.')}</li>
        </ol>
        <button className="secondary-button" disabled={busy} onClick={() => void demo()}>
          {t('Load tutorial project')}
        </button>
      </details>
      {error && <p role="alert">{error}</p>}
      <button className="secondary-button" onClick={() => void reload(id).then(() => setRefresh(v => v + 1))}>
        {t('Refresh navigator')}
      </button>
      <label>
        {t('Saved navigation filter')}
        <input
          type="search"
          value={query}
          onChange={e => {
            setQuery(e.target.value);
            setOffsets({});
            try {
              localStorage.setItem(key, e.target.value);
            } catch {
              /* Optional browser preference. */
            }
          }}
        />
      </label>
      {id && (
        <fieldset>
          <legend>{t('Documentation sections')}</legend>
          {(Object.keys(reportSections) as (keyof typeof reportSections)[]).map(key => (
            <label key={key}>
              <input
                type="checkbox"
                checked={reportSections[key]}
                onChange={e => setReportSections(v => ({ ...v, [key]: e.target.checked }))}
              />
              {t('Report: ' + key)}
            </label>
          ))}
        </fieldset>
      )}
      {id && (
        <button
          className="secondary-button"
          onClick={() =>
            void fetch(
              `/api/workspaces/${id}/documentation?${new URLSearchParams({ language: getLocale(), ...Object.fromEntries(Object.entries(reportSections).map(([k, v]) => [k, String(v)])) })}`,
              { headers: { 'X-Schemora-Token': sessionToken } },
            )
              .then(async response => {
                if (!response.ok) throw Error(t('Documentation export failed.'));
                const url = URL.createObjectURL(await response.blob());
                const a = document.createElement('a');
                a.href = url;
                a.download = 'schemora-schema.html';
                a.click();
                setTimeout(() => URL.revokeObjectURL(url), 1000);
              })
              .catch(e => setError(errorMessage(e, t('Documentation export failed.'))))
          }
        >
          {t('Export schema documentation')}
        </button>
      )}
      {repositories.map(([repository, projects]) => (
        <details key={repository} open>
          <summary title={repository}>{displayPath(repository)}</summary>
          {projects.map(([label, dbs]) => (
            <details key={label} open>
              <summary title={label.split(' → ').slice(1).join(' → ')}>{displayPath(label.split(' → ').slice(1).join(' → '))}</summary>
              {dbs.map(db => (
                <details key={db.id} open>
                  <summary>{db.name}</summary>
                  {[...new Set(db.objects.map(o => o.schema))].map(schema => (
                    <details key={schema} open={Boolean(query)}>
                      <summary>{schema}</summary>
                      {db.objects
                        .filter(o => o.schema === schema && `${o.schema}.${o.name}`.toLowerCase().includes(query.toLowerCase()))
                        .slice(offsets[db.id + schema] || 0, (offsets[db.id + schema] || 0) + 100)
                        .map(o => (
                          <div key={o.id}>
                            <button className="text-button" aria-pressed={selected === o.id} onClick={() => setSelected(o.id)}>
                              {o.name} · {t('Kind: ' + o.kind)}
                            </button>
                            <button
                              className="text-button"
                              onClick={() =>
                                void request<Graph>(`/api/databases/${db.id}/schema`)
                                  .then(graph => {
                                    const database = catalog?.databases.find(d => d.id === db.id);
                                    if (database) onObject(graph, database);
                                  })
                                  .catch(e => setError(errorMessage(e, t('Unable to open schema.'))))
                              }
                            >
                              {t('Open schema')}
                            </button>
                          </div>
                        ))}
                      <div>
                        <button
                          className="text-button"
                          disabled={!offsets[db.id + schema]}
                          onClick={() => setOffsets(v => ({ ...v, [db.id + schema]: Math.max(0, (v[db.id + schema] || 0) - 100) }))}
                        >
                          {t('Previous page')}
                        </button>
                        <span>
                          {(offsets[db.id + schema] || 0) + 1} · {t('Objects per page')}: 100
                        </span>
                        <button
                          className="text-button"
                          disabled={
                            (offsets[db.id + schema] || 0) + 100 >=
                            db.objects.filter(
                              o => o.schema === schema && (o.schema + '.' + o.name).toLowerCase().includes(query.toLowerCase()),
                            ).length
                          }
                          onClick={() => setOffsets(v => ({ ...v, [db.id + schema]: (v[db.id + schema] || 0) + 100 }))}
                        >
                          {t('Next page')}
                        </button>
                      </div>
                    </details>
                  ))}
                </details>
              ))}
            </details>
          ))}
        </details>
      ))}
      {selected && <DependencyPaths workspace={id} objectId={selected} onRecipe={onRecipe} />}
    </section>
  );
}
